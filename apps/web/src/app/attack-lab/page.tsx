import type { Metadata } from 'next';
import { Chip, PageFrame, Section, SourceBanner } from '@/components/product/PageFrame';
import type { ChipTone } from '@/components/product/PageFrame';
import { loadAttackMatrix, loadAttackMeta, loadBundle } from '@/server/recorded';
import type { AttackMatrix } from '@/server/recorded';

export const metadata: Metadata = {
  title: 'Attack lab | Symbolon',
  description: 'Twenty-four attacks against a naive baseline, a pattern reimplementation and Symbolon, judged by an independent oracle.',
};
export const dynamic = 'force-dynamic';

const TARGETS: { id: string; label: string }[] = [
  { id: 'b0', label: 'B0 vendored Circle sample path' },
  { id: 'b1', label: 'B1 pattern reimplementation (ours)' },
  { id: 'b2', label: 'B2 hardened baseline' },
  { id: 'symbolon', label: 'Symbolon' },
];

const OUTCOME_TONE: Record<string, ChipTone> = { BLOCKED: 'pass', ESCALATED: 'pass', HELD: 'pass', NOOP: 'muted', LOSS: 'fail', NOT_RUN: 'muted' };

function cell(m: AttackMatrix, attackId: string, target: string) {
  const row = m.attacks.find((a) => a.attackId === attackId && a.target === target);
  if (row !== undefined) return { kind: 'row' as const, row };
  const app = m.applicability.find((a) => a.attackId === attackId && a.target === target);
  const t = m.targets.find((x) => x.id === target);
  if (app !== undefined && app.applicable === false) return { kind: 'na' as const, reason: app.reason };
  if (t !== undefined && t.status !== 'run') return { kind: 'notbuilt' as const, reason: `${t.status}` };
  return { kind: 'none' as const };
}

export default function Page() {
  const m = loadAttackMatrix();
  const meta = loadAttackMeta();
  const bundle = loadBundle();
  if (m === null) {
    return (
      <PageFrame eyebrow="Attack lab" title="Attack matrix unavailable">
        <p>No recorded attack matrix is available in this deployment. Nothing is shown rather than a made-up result.</p>
      </PageFrame>
    );
  }
  const ids = Array.from(new Set(m.applicability.map((a) => a.attackId))).sort();
  const notApplicable = m.applicability.filter((a) => a.applicable === false);
  const lossRows = m.attacks.filter((a) => a.outcome === 'LOSS');

  return (
    <PageFrame
      eyebrow="Attack lab"
      title="Twenty-four attacks, four targets"
      lede="Each attack runs against the same engagements and documents. An independent oracle decides whether money left that should not have. Results are generated by the harness and rendered here without edits."
    >
      <SourceBanner
        source="RECORDED"
        note={
          <>
            Harness mode <span className="sy-mono">{m.mode}</span>; engagements are fixtures with placeholder signatures and extraction reads are reference reads, so every figure is <Chip tone="warn">SIMULATED</Chip>. Bundle hash{' '}
            <span className="sy-mono">{bundle?.bundleHash ?? 'n/a'}</span>.
          </>
        }
      />

      <Section title="Totals by target">
        <div className="sy-table-wrap">
          <table className="sy-table">
            <thead>
              <tr><th>Target</th><th>Attacks run</th><th>Not applicable</th><th>Trials</th><th>Loss trials</th><th>Loss rate (upper 95 %)</th><th>Loss (base units)</th></tr>
            </thead>
            <tbody>
              {m.totals.map((t) => (
                <tr key={t.target}>
                  <td>{TARGETS.find((x) => x.id === t.target)?.label ?? t.target}</td>
                  <td>{t.applicable} of {t.attacks}</td>
                  <td>{t.notApplicable}</td>
                  <td>{t.trials}</td>
                  <td>{t.lossTrials}</td>
                  <td>
                    {t.lossRate.k}/{t.lossRate.n}, upper {t.lossRate.upper95.toFixed(4)} <span className="body-text-xs">({t.lossRate.upper95Method})</span>
                  </td>
                  <td className="sy-mono">{t.lossBaseUnits}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <p className="body-text-s" style={{ marginTop: 8 }}>
          Trials are runs of committed fixtures; runs of one fixture are not independent, so the upper bounds are optimistic. Targets that are not built are listed below, not hidden.
        </p>
      </Section>

      <Section title="Attack by attack">
        <div className="sy-table-wrap">
          <table className="sy-table">
            <thead>
              <tr>
                <th>Attack</th>
                {TARGETS.map((t) => <th key={t.id}>{t.label}</th>)}
              </tr>
            </thead>
            <tbody>
              {ids.map((id) => (
                <tr key={id}>
                  <td>
                    <span className="sy-mono">{id}</span>
                    <br />
                    <strong>{meta[id]?.title ?? ''}</strong>
                    {meta[id] ? <div className="body-text-xs">{meta[id].caption}</div> : null}
                  </td>
                  {TARGETS.map((t) => {
                    const c = cell(m, id, t.id);
                    return (
                      <td key={t.id}>
                        {c.kind === 'row' ? (
                          <>
                            <Chip tone={OUTCOME_TONE[c.row.outcome] ?? 'muted'}>{c.row.outcome}</Chip>
                            <div className="body-text-xs">{c.row.scoring === 'oracle' ? 'oracle-scored' : 'signal-scored'}</div>
                            {c.row.checksFired.length > 0 ? <div className="body-text-xs sy-mono">{c.row.checksFired.join(' ')}</div> : null}
                          </>
                        ) : c.kind === 'na' ? (
                          <Chip tone="muted">N/A</Chip>
                        ) : c.kind === 'notbuilt' ? (
                          <Chip tone="muted">NOT BUILT</Chip>
                        ) : (
                          <Chip tone="muted">NOT RUN</Chip>
                        )}
                      </td>
                    );
                  })}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Section>

      {lossRows.length > 0 ? (
        <Section title="Where a target lost">
          <ul className="sy-list">
            {lossRows.map((r) => (
              <li key={`${r.attackId}-${r.target}`}>
                <span className="sy-mono">{r.attackId}</span> against <strong>{r.target}</strong>: outcome LOSS ({r.scoring}-scored, loss {r.lossBaseUnits} base units).
                {r.scoring !== 'oracle' || r.lossBaseUnits === '0' ? ' This is a failed stated criterion in the harness, not money moved.' : ''}
              </li>
            ))}
          </ul>
        </Section>
      ) : null}

      {notApplicable.length > 0 ? (
        <Section title="Not applicable, and why">
          <ul className="sy-list">
            {notApplicable.map((a) => (
              <li key={`${a.attackId}-${a.target}`}>
                <span className="sy-mono">{a.attackId}</span> on <strong>{a.target}</strong>: {a.reason}
              </li>
            ))}
          </ul>
        </Section>
      ) : null}

      <Section title="Targets">
        <ul className="sy-list">
          {m.targets.map((t) => (
            <li key={t.id}>
              <strong>{t.label}</strong> <Chip tone={t.status === 'run' ? 'plain' : 'muted'}>{t.status}</Chip>
              <div className="body-text-s">{t.provenance}</div>
            </li>
          ))}
        </ul>
      </Section>

      <Section title="Honest invoices">
        <div className="sy-table-wrap">
          <table className="sy-table">
            <thead><tr><th>Target</th><th>Invoices</th><th>Released</th><th>Released, correct</th><th>Released, loss</th><th>Escalated</th><th>Wrongful rejects</th></tr></thead>
            <tbody>
              {m.honest.map((h) => (
                <tr key={h.target}>
                  <td>{h.target}</td>
                  <td>{h.n}</td>
                  <td>{h.released}</td>
                  <td>{h.releasedCorrect}</td>
                  <td>{h.releasedLoss}</td>
                  <td>{h.escalated}</td>
                  <td>{h.wrongfulReject.k}/{h.wrongfulReject.n}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Section>

      <Section title="Hold-out set">
        <p>
          <Chip tone="muted">{m.holdout.status.toUpperCase()}</Chip> {m.holdout.reason ?? ''}
        </p>
      </Section>

      <Section title="Limitations of this run">
        <ul className="sy-list">
          {m.limitations.map((l) => <li key={l}>{l}</li>)}
        </ul>
      </Section>
    </PageFrame>
  );
}
