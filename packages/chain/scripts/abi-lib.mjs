// Pure helpers shared by gen-abi.mjs and the drift test (test/abi.test.ts).
// The ABI committed in src/abi/symbolonVault.ts is generated from the forge artifact, never typed by hand.
import { createHash } from "node:crypto";

export const ARTIFACT_RELATIVE_PATH = "contracts/out/SymbolonVault.sol/SymbolonVault.json";

/** Extract and validate the ABI array from a forge artifact (parsed JSON). */
export function abiFromArtifact(artifact) {
  if (artifact === null || typeof artifact !== "object" || !Array.isArray(artifact.abi) || artifact.abi.length === 0) {
    throw new Error("forge artifact has no non-empty `abi` array");
  }
  return artifact.abi;
}

/** sha256 over the compact JSON of the ABI: a short fingerprint for diffs and reviews. */
export function abiFingerprint(abi) {
  return createHash("sha256").update(JSON.stringify(abi)).digest("hex");
}

/** The exact text of src/abi/symbolonVault.ts for a given ABI (LF line endings, trailing newline). */
export function renderAbiModule(abi) {
  return [
    "// GENERATED by packages/chain/scripts/gen-abi.mjs from " + ARTIFACT_RELATIVE_PATH + ". DO NOT EDIT.",
    "// Regenerate: `forge build` in contracts/, then `pnpm --filter @symbolon/chain abi:gen`.",
    "// test/abi.test.ts fails if this file differs from the compiled artifact.",
    "// abiSha256: " + abiFingerprint(abi),
    "export const symbolonVaultAbi = " + JSON.stringify(abi, null, 2) + " as const;",
    "",
  ].join("\n");
}
