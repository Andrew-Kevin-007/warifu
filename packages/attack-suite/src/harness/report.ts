// Markdown + JSON for results/attack-matrix.* (docs/07 §5). Every number printed here is read from the AttackMatrix
// that the harness computed; none is typed by hand (INV-18). The wording follows docs/16 §4.3: counts, n, k and the
// 95 % upper bound next to every claim, and the reasons next to every exclusion.
import { asciiJson } from "../files";
import type { AttackMatrix, TargetTotals } from "./matrix";
import type { AttackResult } from "./results";
import { ATTACK_META } from "../attack-meta";

export function formatUsdc(baseUnits: bigint, decimals = 6): string {
  const unit = 10n ** BigInt(decimals);
  const whole = baseUnits / unit;
  const frac = (baseUnits % unit).toString().padStart(decimals, "0");
  return `${whole.toString()}.${frac}`;
}

const pct = (x: number): string => `${(x * 100).toFixed(2)}%`;

function totalsOf(m: AttackMatrix, target: string): TargetTotals {
  const t = m.totals.find((x) => x.target === target);
  if (t === undefined) throw new RangeError(`no totals for ${target}`);
  return t;
}

function lossLine(t: TargetTotals): string {
  const y = t.applicable;
  const x = t.oracleScored.loss + t.signalScored.loss;
  return `${x} of ${y} applicable attacks (oracle-scored ${t.oracleScored.loss} of ${t.oracleScored.applicable}; signal-scored ${t.signalScored.loss} of ${t.signalScored.applicable}; not run at all ${t.oracleScored.notRun + t.signalScored.notRun})`;
}

function rateLine(t: TargetTotals): string {
  const r = t.lossRate;
  if (r === null) return "no trials";
  const method = r.upper95Method === "rule-of-three" ? "rule of three, 3/n" : "Clopper-Pearson";
  return `${r.k} oracle-judged loss(es) in ${r.n} trials (95% upper bound ${pct(r.upper95)}, ${method}); trials of one fixture are not independent`;
}

function cell(r: AttackResult | undefined): string {
  if (r === undefined) return "-";
  if (r.outcome === "N/A") return "N/A";
  return r.complete ? r.outcome : `${r.outcome} (partial)`;
}

export function renderMarkdown(m: AttackMatrix): string {
  const sym = totalsOf(m, "symbolon");
  const b1 = totalsOf(m, "b1");
  const b0 = totalsOf(m, "b0");
  const b2 = totalsOf(m, "b2");
  const symT = m.targets.find((t) => t.id === "symbolon");
  const out: string[] = [];
  const p = (s = ""): void => void out.push(s);

  p("# Attack matrix (unit mode)");
  p();
  p("Generated by `pnpm attack:unit` from the committed fixtures; do not edit by hand. Every number below is computed by the harness (INV-18).");
  p();
  p("## Headline");
  p();
  const byCriterionOnly = m.attacks.filter((a) => a.target === "symbolon" && a.outcome === "LOSS" && (a.oracle?.lossReleases ?? 0) === 0).length;
  p(`- **Symbolon (unit mode, real kernel-core pipeline):** loss on ${lossLine(sym)}. ${rateLine(sym)}. ${byCriterionOnly} of the attacks counted as loss are counted on a failed stated criterion or ledger signal with no oracle-judged loss.`);
  const unimpl = symT?.unimplementedChecks ?? [];
  if (symT?.releasePathAvailable === true) {
    const symReleases = m.attacks.filter((a) => a.target === "symbolon").reduce((n, a) => n + (a.oracle?.releases ?? 0), 0);
    p(
      `- **Release path available in this build: yes** (no check is a fail-closed placeholder). The oracle judged ${symReleases} real RELEASE verdict(s) of Symbolon across the attacks, so the count above is measured against a kernel that can pay. ` +
        "Read it with the expectation mismatches below: where an earlier check (K-04) rejects first, the later checks the attack was designed for are not exercised in that run.",
    );
  } else {
    p(
      `- **Read this with the next line.** Release path available in this build: **no**` +
        (unimpl.length > 0 ? ` (checks not implemented: ${unimpl.join(", ")}; they fail closed to HOLD, so no intent can reach RELEASE).` : ".") +
        " With no release path a loss count of 0 says nothing about the checks that are missing; it only shows the implemented checks and the fail-closed default hold.",
    );
  }
  const failedCriteria = m.attacks.filter((a) => a.target === "symbolon" && a.criteria.failed > 0);
  const passedAll = m.attacks.filter((a) => a.target === "symbolon").reduce((n, a) => n + a.criteria.passed, 0);
  const failedAll = m.attacks.filter((a) => a.target === "symbolon").reduce((n, a) => n + a.criteria.failed, 0);
  p(
    `- **Human-loop criteria (ATK-22 digest, ATK-23 approval rendering, ATK-24 explainer; unit mode):** ${passedAll} of ${passedAll + failedAll} met` +
      (failedCriteria.length > 0 ? `; NOT met in ${failedCriteria.map((a) => a.attackId).join(", ")} (those attacks are counted as LOSS above on a criterion, not on money: see the criteria section)` : "") +
      ".",
  );
  p(`- **B1 (naive release-on-model-output pattern, ours, SIMULATED validator):** loses on ${lossLine(b1)}. ${rateLine(b1)}.`);
  p(`- **B0 (vendored arc-escrow validate-work path, edges stubbed, SIMULATED model, pinned ${m.provenance.b0Revision.slice(0, 12)}):** loses on ${lossLine(b0)}. ${rateLine(b0)}. Attacks it holds by design are measured and listed, not dropped.`);
  p(`- **B2 (reasonable hardening, ours):** loses on ${lossLine(b2)}. ${rateLine(b2)}.`);
  p(`- **Complete attacks:** Symbolon ${sym.completeAttacks} of ${sym.applicable} ran every step; the others are partial or NOT_RUN (reasons below). NOT_RUN is never counted as blocked.`);
  p(`- **Oracle/fixture agreement:** ${m.agreement.rows} intended releases checked, ${m.agreement.disagreements} disagreement(s) (must be 0); ${m.agreement.extrasInformational} release(s) break more rules than the fixture lists (information only).`);
  p(`- **Hold-out:** ${m.holdout.status.replace("-", " ")}. ${m.holdout.reason.charAt(0).toUpperCase()}${m.holdout.reason.slice(1)}.`);
  p();

  p("## Targets and provenance");
  p();
  p("| Target | Status | What it is |");
  p("|---|---|---|");
  for (const t of m.targets) p(`| ${t.id} | ${t.status} | ${t.provenance} |`);
  p();
  p(`Oracle: ${m.oracleVersion} (packages/oracle). Harness: ${m.harness}. Fixtures: ${m.provenance.fixtureGenerator}, seed \`${m.provenance.seed}\`, manifest sha256 \`${m.provenance.fixtureManifestSha256}\`. Git SHA of the code that ran: ${m.provenance.gitSha ?? "not recorded"}. Models: ${m.provenance.models}. Recorded LLM outputs: none. Anvil fork block: none (unit mode).`);
  p();
  p("B1 reference-validator rules (a deterministic stand-in for an LLM validator prompt):");
  p();
  for (const r of m.provenance.b1ValidatorRules) p(`- ${r}`);
  p();
  p("B0 and B2 use the same SIMULATED validator rules for the model's answer (B0 maps LOW-confidence rules to MEDIUM, which its vendored route also refuses to pay). B2's hardening controls:");
  p();
  for (const r of m.provenance.b2Controls) p(`- ${r}`);
  p();

  p("## Attack matrix");
  p();
  p("Outcome per target. `LOSS` is decided by the oracle on the releases the target made (scoring \"oracle\") or, for the five attacks the oracle cannot express, by a documented signal (scoring \"signal\"). Loss in USDC is the money that left the correct-payee/correct-amount rule; a rule violation with the right payee and amount shows 0.000000.");
  p();
  p("| Attack | Class | Scoring | Symbolon | checks fired | expectations (match/mismatch/inconclusive) | Symbolon control | B0 | B0 loss (USDC) | B0 oracle predicates | B1 | B1 loss (USDC) | B1 oracle predicates | B1 control | B2 | B2 loss (USDC) | B2 oracle predicates |");
  p("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  const baseline = (r: AttackResult | undefined): string[] =>
    r === undefined || r.outcome === "N/A" ? [cell(r), "", ""] : [cell(r), formatUsdc(BigInt(r.lossBaseUnits)), r.oracle?.predicates.join("+") ?? ""];
  for (const id of ATTACK_META_IDS) {
    const find = (t: string): AttackResult | undefined => m.attacks.find((a) => a.attackId === id && a.target === t);
    const s = find("symbolon");
    const b1 = find("b1");
    const meta = ATTACK_META[id];
    const cols = [
      id, meta.errorClass, s?.scoring ?? "-", cell(s), s?.checksFired.join(", ") ?? "",
      s === undefined ? "" : `${s.expectations.match}/${s.expectations.mismatch}/${s.expectations.inconclusive}`,
      s?.control.status ?? "",
      ...baseline(find("b0")),
      ...baseline(b1),
      b1 === undefined || b1.outcome === "N/A" ? "" : b1.control.status,
      ...baseline(find("b2")),
    ];
    p(`| ${cols.join(" | ")} |`);
  }
  p();

  p("### Not applicable (listed, never dropped)");
  p();
  for (const r of m.attacks.filter((a) => a.outcome === "N/A")) p(`- ${r.attackId} x ${r.target}: ${r.notes.join(" ")}`);
  const undecided = m.applicability.filter((r) => r.applicable === null);
  p(`- ${undecided.length} applicability row(s) are undecided (packages/attack-suite/fixtures/applicability.json carries a reason for every row).`);
  p();

  p("### Steps the Symbolon target did not run (NOT_RUN)");
  p();
  for (const a of m.attacks.filter((x) => x.target === "symbolon")) {
    for (const s of a.steps.filter((x) => x.status === "NOT_RUN")) p(`- ${s.stepId} (${s.kind}): ${s.reason}`);
  }
  p();

  p("### Human-loop criteria (Symbolon, unit mode)");
  p();
  p("Stated criteria of ATK-22/23/24 (docs/07 §3.2). They test the kernel's escalation budget and digest, the packages/receipts WYSIWYS comparator and the templated explainer; whether the web screen really disables Sign is WP-19/SEC-13, not measured here.");
  p();
  for (const a of m.attacks.filter((x) => x.target === "symbolon" && (x.criteria.passed + x.criteria.failed) > 0)) {
    p(`- ${a.attackId}: ${a.criteria.passed} met, ${a.criteria.failed} not met.`);
    for (const s of a.steps) for (const c of s.criteria.filter((x) => !x.passed)) p(`  - NOT MET ${c.id}: ${c.detail}`);
  }
  p();

  p("### Expectation mismatches (Symbolon, unit mode)");
  p();
  p("A MISMATCH is an implemented check disagreeing with the fixture's expectation; INCONCLUSIVE means the expectation needs a check this build lacks.");
  p();
  const groups = new Map<string, { n: number; example: string }>();
  for (const a of m.attacks.filter((x) => x.target === "symbolon")) {
    for (const s of a.steps) {
      for (const r of s.runs.filter((x) => x.expectation === "MISMATCH")) {
        const g = groups.get(a.attackId) ?? { n: 0, example: `${s.stepId} [${r.label}]: ${r.expectationNote}` };
        groups.set(a.attackId, { n: g.n + 1, example: g.example });
      }
    }
  }
  if (groups.size === 0) p("None.");
  for (const [id, g] of groups) p(`- ${id}: ${g.n} run(s). First: ${g.example}`);
  p();

  p("## Honest corpus (the 12 spec-named fixtures; the wider corpus is WP-24)");
  p();
  p("| Target | n | released | released correctly | released with loss or wrong amount | rejected | escalated | held | held only by missing checks |");
  p("|---|---|---|---|---|---|---|---|---|");
  for (const h of m.honest) p(`| ${h.target} | ${h.n} | ${h.released} | ${h.releasedCorrect} | ${h.releasedLoss} | ${h.rejected} | ${h.escalated} | ${h.held} | ${h.heldByUnimplementedChecks} |`);
  p();
  for (const h of m.honest) {
    p(`- ${h.target}: wrongful-reject ${h.wrongfulReject.k} of ${h.wrongfulReject.n} (Wilson 95%: ${pct(h.wrongfulReject.wilsonLower)} to ${pct(h.wrongfulReject.wilsonUpper)}).`);
  }
  p();

  p("## Known limits");
  p();
  for (const l of m.limitations) p(`- ${l}`);
  p();
  p("## Reproduce");
  p();
  p("```");
  p("pnpm install --frozen-lockfile");
  p("pnpm --filter @symbolon/attack-suite attack:unit      # rewrites results/attack-matrix.json and .md");
  p("pnpm exec vitest run packages/attack-suite packages/oracle");
  p("```");
  p();
  return `${out.join("\n")}\n`;
}

const ATTACK_META_IDS = Object.keys(ATTACK_META).sort() as Array<keyof typeof ATTACK_META>;

export function renderJson(m: AttackMatrix): string {
  return asciiJson(m);
}
